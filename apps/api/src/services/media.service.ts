import { randomUUID } from 'node:crypto';
import { MEDIA_WIDTHS, mediaUrl, type ListQuery, type MediaWidth } from '@shop/shared';
import type { StorageDriver } from '../integrations/storage/storage-driver';
import { AppError } from '../lib/errors';
import { detectImageKind, ImageRejectedError, processImage } from '../lib/image';
import type { Db } from '../lib/prisma';
import * as repo from '../repositories/media.repository';
import { findSettingValue } from '../repositories/settings.repository';
import { recordAudit, type Actor } from './audit.service';

export type MediaServiceDeps = { prisma: Db; storage: StorageDriver; publicMediaUrl: string };

type MediaRow = NonNullable<Awaited<ReturnType<typeof repo.findMedia>>>;
export type MediaDto = MediaRow & { urls: Record<MediaWidth, string> };

export function toMediaDto(row: MediaRow, publicMediaUrl: string): MediaDto {
  const urls = Object.fromEntries(
    MEDIA_WIDTHS.map((w) => [w, mediaUrl(publicMediaUrl, row.path, w)]),
  ) as Record<MediaWidth, string>;
  return { ...row, urls };
}

const fileKey = (path: string, width: MediaWidth) => `${path}-${width}.webp`;

export type MediaFolder = 'products' | 'reviews';

/** <folder>/YYYY/MM/<uuid>: generated by us; the uploaded file name is never used (CLAUDE.md). */
function newMediaPath(folder: MediaFolder, now = new Date()): string {
  const month = String(now.getUTCMonth() + 1).padStart(2, '0');
  return `${folder}/${now.getUTCFullYear()}/${month}/${randomUUID()}`;
}

/**
 * Validates the real file type from its bytes, re-encodes it with sharp (metadata stripped), writes
 * every size, then records the media row. Files are removed again if the database insert fails.
 */
export async function uploadMedia(
  deps: MediaServiceDeps,
  /** null for a customer's review photo (no admin, no audit row). */
  actor: Actor | null,
  input: { body: Buffer; altText: string; folder?: MediaFolder },
): Promise<MediaDto> {
  const kind = detectImageKind(input.body);
  if (!kind)
    throw new AppError('VALIDATION_ERROR', 'Only JPEG, PNG and WebP images are allowed', [
      { path: 'file', message: 'Unsupported file type' },
    ]);

  let processed;
  try {
    processed = await processImage(input.body, kind);
  } catch (err) {
    if (err instanceof ImageRejectedError)
      throw new AppError('VALIDATION_ERROR', err.message, [{ path: 'file', message: err.message }]);
    throw err;
  }

  const path = newMediaPath(input.folder ?? 'products');
  const written: string[] = [];
  try {
    for (const out of processed.outputs) {
      const key = fileKey(path, out.width);
      await deps.storage.put(key, out.body, 'image/webp');
      written.push(key);
    }
    const row = await deps.prisma.$transaction(async (tx) => {
      const media = await repo.createMedia(tx, {
        path,
        mime: 'image/webp',
        sizeBytes: input.body.length,
        width: processed.width,
        height: processed.height,
        altText: input.altText,
        uploadedById: actor?.adminUserId ?? null,
      });
      if (actor)
        await recordAudit(tx, actor, {
          action: 'media.upload',
          entityType: 'media',
          entityId: media.id,
          after: { path, altText: input.altText, width: processed.width, height: processed.height },
        });
      return media;
    });
    return toMediaDto(row, deps.publicMediaUrl);
  } catch (err) {
    await Promise.allSettled(written.map((key) => deps.storage.delete(key)));
    throw err;
  }
}

export async function listMedia(deps: MediaServiceDeps, query: ListQuery) {
  const { items, total } = await repo.listMedia(deps.prisma, query);
  return { items: items.map((m) => toMediaDto(m, deps.publicMediaUrl)), total };
}

async function existing(prisma: Db, id: string): Promise<MediaRow> {
  const media = await repo.findMedia(prisma, id);
  if (!media) throw new AppError('NOT_FOUND', 'Image not found');
  return media;
}

export async function updateMediaAlt(
  deps: MediaServiceDeps,
  actor: Actor,
  id: string,
  altText: string,
): Promise<MediaDto> {
  const before = await existing(deps.prisma, id);
  const row = await deps.prisma.$transaction(async (tx) => {
    const updated = await repo.updateMediaAlt(tx, id, altText);
    await recordAudit(tx, actor, {
      action: 'media.update',
      entityType: 'media',
      entityId: id,
      before: { altText: before.altText },
      after: { altText },
    });
    return updated;
  });
  return toMediaDto(row, deps.publicMediaUrl);
}

/**
 * Refused while any product, category, brand, banner or review still uses the image, or while it is
 * the store logo (the `store.logo` setting holds the image's URL, not its id).
 */
export async function deleteMedia(deps: MediaServiceDeps, actor: Actor, id: string): Promise<void> {
  const media = await existing(deps.prisma, id);
  const logo = await findSettingValue(deps.prisma, 'store.logo');
  if (typeof logo === 'string' && logo.includes(`/${media.path}-`)) {
    throw new AppError(
      'CONFLICT',
      'This image is the store logo. Choose another logo in Settings first.',
      [{ reason: 'MEDIA_IN_USE' }],
    );
  }
  if ((await repo.countMediaReferences(deps.prisma, id)) > 0) {
    throw new AppError(
      'CONFLICT',
      'This image is still in use. Remove it from products, categories and banners first.',
      [{ reason: 'MEDIA_IN_USE' }],
    );
  }
  await deps.prisma.$transaction(async (tx) => {
    await repo.deleteMedia(tx, id);
    await recordAudit(tx, actor, {
      action: 'media.delete',
      entityType: 'media',
      entityId: id,
      before: { path: media.path, altText: media.altText },
    });
  });
  // Files go after the row: a failed file delete leaves an orphan file, never a broken image.
  await Promise.allSettled(MEDIA_WIDTHS.map((w) => deps.storage.delete(fileKey(media.path, w))));
}

/**
 * Review photos uploaded but never attached to a review (abandoned forms) are deleted after a day,
 * files first then rows. Only the `reviews/` folder is touched; shop images are never removed here.
 */
export async function cleanupOrphanReviewPhotos(
  deps: Pick<MediaServiceDeps, 'prisma' | 'storage'>,
  now = new Date(),
) {
  const orphans = await deps.prisma.media.findMany({
    where: {
      path: { startsWith: 'reviews/' },
      createdAt: { lt: new Date(now.getTime() - 24 * 60 * 60 * 1000) },
      reviewImages: { none: {} },
    },
    select: { id: true, path: true },
    take: 200,
  });
  for (const m of orphans) {
    await Promise.allSettled(MEDIA_WIDTHS.map((w) => deps.storage.delete(fileKey(m.path, w))));
    await deps.prisma.media.delete({ where: { id: m.id } }).catch(() => undefined);
  }
  return orphans.length;
}
